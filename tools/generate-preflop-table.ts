/**
 * Generates src/equity/preflopData.ts: Monte Carlo equity of each of the 169
 * starting hands against 1, 2, 3, 5 and 8 random opponents, plus a strength order.
 * Run: node tools/run-ts.mjs tools/generate-preflop-table.ts
 */
import { writeFileSync } from 'node:fs';
import { makeCard, RANK_CHARS } from '../src/engine/cards';
import { scoreHand } from '../src/engine/evaluator';
import { SeededRng } from '../src/engine/rng';

const OPPONENT_COUNTS = [1, 2, 3, 5, 8];
const SAMPLES = [500000, 200000, 120000, 70000, 50000];

const rng = new SeededRng('preflop-table-v1');

function simulate(c1: number, c2: number, opponents: number, samples: number): number {
  const deck: number[] = [];
  for (let c = 0; c < 52; c++) if (c !== c1 && c !== c2) deck.push(c);
  const n = deck.length;
  const need = 5 + opponents * 2;
  const hero = new Int32Array(7);
  const villain = new Int32Array(7);
  hero[0] = c1;
  hero[1] = c2;
  let sum = 0;
  for (let s = 0; s < samples; s++) {
    for (let i = 0; i < need; i++) {
      const j = i + rng.int(n - i);
      const t = deck[i];
      deck[i] = deck[j];
      deck[j] = t;
    }
    for (let i = 0; i < 5; i++) {
      hero[i + 2] = deck[i];
      villain[i + 2] = deck[i];
    }
    const h = scoreHand(hero, 7);
    let beaten = false;
    let tied = 0;
    for (let v = 0; v < opponents; v++) {
      villain[0] = deck[5 + v * 2];
      villain[1] = deck[6 + v * 2];
      const score = scoreHand(villain, 7);
      if (score > h) {
        beaten = true;
        break;
      }
      if (score === h) tied++;
    }
    if (!beaten) sum += 1 / (tied + 1);
  }
  return sum / samples;
}

const classes: Array<{ name: string; c1: number; c2: number; size: number }> = [];
for (let hi = 12; hi >= 0; hi--) {
  for (let lo = hi; lo >= 0; lo--) {
    if (hi === lo) classes.push({ name: RANK_CHARS[hi] + RANK_CHARS[lo], c1: makeCard(hi, 0), c2: makeCard(lo, 1), size: 6 });
    else {
      classes.push({ name: `${RANK_CHARS[hi]}${RANK_CHARS[lo]}s`, c1: makeCard(hi, 0), c2: makeCard(lo, 0), size: 4 });
      classes.push({ name: `${RANK_CHARS[hi]}${RANK_CHARS[lo]}o`, c1: makeCard(hi, 0), c2: makeCard(lo, 1), size: 12 });
    }
  }
}

const started = Date.now();
const table: Record<string, number[]> = {};
for (const cls of classes) {
  table[cls.name] = OPPONENT_COUNTS.map((opp, i) => Number(simulate(cls.c1, cls.c2, opp, SAMPLES[i]).toFixed(4)));
}

// Strength order blends heads-up and multiway equity (normalised by the fair share)
// so that small pairs and suited connectors rank sensibly against big offsuit cards.
const blended = (name: string): number => {
  const e = table[name];
  return 0.5 * (e[0] / 0.5) + 0.25 * (e[1] / (1 / 3)) + 0.15 * (e[2] / 0.25) + 0.1 * (e[3] / (1 / 6));
};
const order = classes.map((c) => c.name).sort((a, b) => blended(b) - blended(a));

const body = `// GENERATED by tools/generate-preflop-table.ts. Do not edit by hand.
// Monte Carlo equity against [1, 2, 3, 5, 8] random opponents, samples per class: ${SAMPLES.join(', ')}.
export const PREFLOP_OPPONENT_COUNTS = [${OPPONENT_COUNTS.join(', ')}] as const;

export const PREFLOP_EQUITY: Readonly<Record<string, readonly number[]>> = {
${classes.map((c) => `  '${c.name}': [${table[c.name].join(', ')}],`).join('\n')}
};

/** Starting hand classes from strongest to weakest. */
export const PREFLOP_ORDER: readonly string[] = [
${order.map((n) => `'${n}'`).join(', ')},
];
`;
writeFileSync('src/equity/preflopData.ts', body);
console.log(`Generated ${classes.length} classes in ${((Date.now() - started) / 1000).toFixed(1)}s`);
console.log('Top 20:', order.slice(0, 20).join(' '));
console.log('AA vs 1:', table['AA'][0], ' 72o vs 1:', table['72o'][0]);
